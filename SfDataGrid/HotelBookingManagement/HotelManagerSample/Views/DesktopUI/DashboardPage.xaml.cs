    /// <param name="sender">The tapped sidebar entry. Unused.</param>
    /// <param name="e">Event payload. Unused.</param>
    private async void OnReportsClicked(object? sender, EventArgs e) => await DisplayAlertAsync("Info", "Reports page not implemented yet.", "OK");
    /// <summary>Placeholder "coming soon" handler for the Settings
