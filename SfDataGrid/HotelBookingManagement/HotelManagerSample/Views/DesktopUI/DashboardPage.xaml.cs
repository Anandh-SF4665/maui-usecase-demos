using System.Linq;
using HotelManagerSample;
using Syncfusion.Maui.DataGrid.DataPager;

namespace HotelManagerSample;

/// <summary>
/// Code-behind for the desktop Dashboard page. Owns the navigation
/// hops that surface the Bookings / Rooms pages, the active-state
/// styling for the revenue-range toggle, the segmented pill between
/// "Today's Check-Ins" / "Pending Payment", and the inline search
/// clear-glyph behaviour. All data work flows through the shared
/// <see cref="DashboardViewModel"/> resolved from DI.
/// </summary>
public partial class DashboardPage : ContentPage
{
    /// <summary>Constructs the page, inflates the XAML, wires the
    /// shared view-model, and applies the initial revenue-range
    /// active state. The MAUI XAML inflator produces the
    /// <c>Revenue7DLabel</c> / <c>Revenue1MLabel</c> /
    /// <c>Revenue3MLabel</c> fields automatically when Runtime
    /// XAML inflation is enabled; we only have to read them back so
    /// the toggle handler can re-style them after a tap.</summary>
    public DashboardPage()
    {
        InitializeComponent();

        // TitleBarController.Apply() (called from App.xaml.cs OnLaunched)
        // already flips ExtendsContentIntoTitleBar = true and paints the
        // chrome in #F6F8FD, so the original XAML padding stays — no
        // additional Windows-only inset is needed.

        // Resolve the SHARED view-model from the DI container so the
        // dashboard reads from the same IHotelStore instance the bookings
        // page writes to. Booking additions on the bookings page fire
        // IHotelStore.BookingsChanged which updates the dashboard's KPI
        // tiles, donut-shaped inventory and grid in one cascade.
        App.CaptureServices();
        var vm = App.Services!.GetRequiredService<DashboardViewModel>();
        BindingContext = vm;

        // Subscribe to VM filter changes so we can reset the SfDataPager back
        // to page 1 whenever the VisibleBookings list is rebuilt. Otherwise
        // a search can leave the user on an empty/out-of-range page.
        vm.PagerResetRequested += OnPagerResetRequested;

        // Keep the small "×" clear-search chip in sync with the Entry state.

        // Resolve named labels for active-state styling.
        var revenue7DLabel = this.FindByName<Label>("Revenue7DLabel");
        var revenue1MLabel = this.FindByName<Label>("Revenue1MLabel");
        var revenue3MLabel = this.FindByName<Label>("Revenue3MLabel");

        // Default active state (7D)
        if (revenue7DLabel is not null)
        {
            revenue7DLabel.TextColor = Color.FromArgb("#4A43E6");
            revenue7DLabel.FontAttributes = FontAttributes.Bold;
        }
        if (revenue1MLabel is not null)
        {
            revenue1MLabel.TextColor = Color.FromArgb("#3B4860");
            revenue1MLabel.FontAttributes = FontAttributes.None;
        }
        if (revenue3MLabel is not null)
        {
            revenue3MLabel.TextColor = Color.FromArgb("#3B4860");
            revenue3MLabel.FontAttributes = FontAttributes.None;
        }

        // Apply to fields generated by XAML (avoid CS0229/CS0229 ambiguity)
        // by storing them back into the generated names.
        Revenue7DLabel = revenue7DLabel;
        Revenue1MLabel = revenue1MLabel;
        Revenue3MLabel = revenue3MLabel;
    }

    /// <summary>Toggles the revenue range ("7D" / "1M" / "3M") and
    /// reapplies the active-state styling on the three labels so the
    /// currently-selected range renders in the brand purple.</summary>
    /// <param name="sender">The tapped Label. Used to read its
    /// current text which doubles as the range key.</param>
    /// <param name="e">Tapped-event payload. Unused.</param>
    private void OnRevenueRangeTapped(object? sender, EventArgs e)
    {
        if (BindingContext is not DashboardViewModel vm)
            return;

        if (sender is not Label label)
            return;

        var range = label.Text;
        vm.SetRevenueRange(range);

        // Active-state styling (match expected UI)
        if (Revenue7DLabel is not null && Revenue1MLabel is not null && Revenue3MLabel is not null)
        {
            var is7D = string.Equals(range, "7D", StringComparison.OrdinalIgnoreCase);
            var is1M = string.Equals(range, "1M", StringComparison.OrdinalIgnoreCase);
            var is3M = string.Equals(range, "3M", StringComparison.OrdinalIgnoreCase);

            Revenue7DLabel.TextColor = is7D ? Color.FromArgb("#4A43E6") : Color.FromArgb("#3B4860");
            Revenue7DLabel.FontAttributes = is7D ? FontAttributes.Bold : FontAttributes.None;

            Revenue1MLabel.TextColor = is1M ? Color.FromArgb("#4A43E6") : Color.FromArgb("#3B4860");
            Revenue1MLabel.FontAttributes = is1M ? FontAttributes.Bold : FontAttributes.None;

            Revenue3MLabel.TextColor = is3M ? Color.FromArgb("#4A43E6") : Color.FromArgb("#3B4860");
            Revenue3MLabel.FontAttributes = is3M ? FontAttributes.Bold : FontAttributes.None;
        }
    }

    // Sidebar navigation is owned by HotelManagerSample.Controls.AppSidebar;
    // OnBookingsClicked / OnRoomsClicked have been removed.

