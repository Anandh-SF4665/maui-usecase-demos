    /// sidebar entry. Pops a friendly info alert until the page lands.</summary>
    /// <param name="sender">The tapped sidebar entry. Unused.</param>
    /// <param name="e">Event payload. Unused.</param>
    private async void OnGuestsClicked(object? sender, EventArgs e) => await DisplayAlertAsync("Info", "Guests page not implemented yet.", "OK");
    /// <summary>Placeholder "coming soon" handler for the Calendar
